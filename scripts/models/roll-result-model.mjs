/**
 * ============================================================================
 * WFRP1e Foundry VTT System
 * Roll Result Model
 * ----------------------------------------------------------------------------
 * Immutable description of a completed roll.
 *
 * This class contains result data only.
 * It performs no calculations.
 * ============================================================================
 */

export class RollResult {
	/**
	 * @param {object} options
	 */
	constructor(options = {}) {
		/**
		 * Original RollRequest.
		 *
		 * @type {RollRequest|null}
		 */
		this.request = options.request ?? null;

		/**
		 * RollContext used during execution.
		 *
		 * @type {RollContext|null}
		 */
		this.context = options.context ?? null;

		/**
		 * Foundry Roll instance.
		 *
		 * @type {Roll|null}
		 */
		this.roll = options.roll ?? null;

		/**
		 * Raw d100 result.
		 *
		 * @type {number}
		 */
		this.value = Number(options.value ?? 0);

		/**
		 * Final target after modifiers.
		 *
		 * @type {number}
		 */
		this.target = Number(options.target ?? 0);

		/**
		 * Final applied modifier.
		 *
		 * @type {number}
		 */
		this.modifier = Number(options.modifier ?? 0);

		/**
		 * Success flag.
		 *
		 * @type {boolean}
		 */
		this.success = Boolean(options.success);

		/**
		 * Failure flag.
		 *
		 * @type {boolean}
		 */
		this.failure = Boolean(options.failure);

		/**
		 * Critical success.
		 *
		 * @type {boolean}
		 */
		this.critical = Boolean(options.critical);

		/**
		 * Critical failure (fumble).
		 *
		 * @type {boolean}
		 */
		this.fumble = Boolean(options.fumble);

		/**
		 * Success Levels.
		 *
		 * @type {number}
		 */
		this.successLevels = Number(options.successLevels ?? 0);

		/**
		 * Degrees of Success / Failure.
		 *
		 * Reserved for optional rules.
		 *
		 * @type {number}
		 */
		this.degrees = Number(options.degrees ?? 0);

		/**
		 * Margin between target and roll.
		 *
		 * Positive = success.
		 * Negative = failure.
		 *
		 * @type {number}
		 */
		this.margin = Number(options.margin ?? 0);

		/**
		 * Damage generated by the roll.
		 *
		 * Primarily used by combat tests.
		 *
		 * @type {number|null}
		 */
		this.damage = options.damage ?? null;

		/**
		 * Hit location.
		 *
		 * head
		 * body
		 * leftArm
		 * rightArm
		 * leftLeg
		 * rightLeg
		 *
		 * @type {string|null}
		 */
		this.hitLocation = options.hitLocation ?? null;

		/**
		 * Chat message id.
		 *
		 * Assigned by ChatService.
		 *
		 * @type {string|null}
		 */
		this.chatMessageId = options.chatMessageId ?? null;

		/**
		 * Additional runtime metadata.
		 *
		 * @type {object}
		 */
		this.metadata = foundry.utils.deepClone(options.metadata ?? {});

		Object.freeze(this.metadata);
		Object.freeze(this);
	}
}
